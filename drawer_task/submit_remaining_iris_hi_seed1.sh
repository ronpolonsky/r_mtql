#!/bin/bash
set -euo pipefail
cd /iris/u/ronpo/projects/new_mtql

LAUNCHER=drawer_task/train.sh
PROJECT=offline-drawer-task-v1-controlled

# Four jobs. Together with the already-running H24/S80 BC+RL anchor, this uses
# six iris-hi slots total.
sbatch --partition=iris-hi \
  --export=ALL,WANDB_PROJECT="$PROJECT",RUN_KIND=bc,SETTING_ID=bc_s25_h32_s64_seed1,TRAIN_SEED=1,TRAIN_STEPS=300000,NUM_SUCCESS_DEMOS=25,NUM_FAILURE_DEMOS=0,HIST_LENGTH=32,HIST_STRIDE=64,BC_BATCH_SIZE=8 \
  "$LAUNCHER"

sbatch --partition=iris-hi \
  --export=ALL,WANDB_PROJECT="$PROJECT",RUN_KIND=rl,SETTING_ID=rl_s25_f15_h32_s64_a300_g999_seed1,TRAIN_SEED=1,TRAIN_STEPS=300000,NUM_SUCCESS_DEMOS=25,NUM_FAILURE_DEMOS=15,HIST_LENGTH=32,HIST_STRIDE=64,ALPHA=300,DISCOUNT=0.999,NORM_Q=true,RL_BATCH_SIZE=8 \
  "$LAUNCHER"

sbatch --partition=iris-hi \
  --export=ALL,WANDB_PROJECT="$PROJECT",RUN_KIND=rl,SETTING_ID=rl_s25_f15_h24_s80_a300_g9995_seed1,TRAIN_SEED=1,TRAIN_STEPS=300000,NUM_SUCCESS_DEMOS=25,NUM_FAILURE_DEMOS=15,HIST_LENGTH=24,HIST_STRIDE=80,ALPHA=300,DISCOUNT=0.9995,NORM_Q=true,RL_BATCH_SIZE=8 \
  "$LAUNCHER"

sbatch --partition=iris-hi \
  --export=ALL,WANDB_PROJECT="$PROJECT",RUN_KIND=rl,SETTING_ID=rl_s25_f15_h24_s80_a1000_g9995_seed1,TRAIN_SEED=1,TRAIN_STEPS=300000,NUM_SUCCESS_DEMOS=25,NUM_FAILURE_DEMOS=15,HIST_LENGTH=24,HIST_STRIDE=80,ALPHA=1000,DISCOUNT=0.9995,NORM_Q=true,RL_BATCH_SIZE=8 \
  "$LAUNCHER"
